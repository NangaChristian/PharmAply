// Detect initial language: localStorage -> browser language -> fallback 'fr'
export function getInitialLanguage(): string {
  if (typeof window === 'undefined') return 'fr';
  
  const saved = localStorage.getItem('appLanguage');
  if (saved && ['fr', 'en', 'ar'].includes(saved)) {
    return saved;
  }

  const browserLang = navigator.language?.split('-')[0]?.toLowerCase();
  if (browserLang && ['fr', 'en', 'ar'].includes(browserLang)) {
    return browserLang;
  }

  return 'fr';
}

const initialLang = getInitialLanguage();

i18n
  .use(initReactI18next)
  .init({
    resources,
    lng: initialLang,
    fallbackLng: 'fr',
    interpolation: {
      escapeValue: false
    }
  });

i18n.on('languageChanged', (lng) => {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lng;
    document.documentElement.dir = i18n.dir(lng);
    localStorage.setItem('appLanguage', lng);
  }
});

if (typeof document !== 'undefined') {
  document.documentElement.lang = i18n.language || initialLang;
  document.documentElement.dir = i18n.dir(i18n.language || initialLang);
}

export default i18n;
