// Helper to generate pseudo-localized text for QA & hardcoded string audits
export function pseudoLocalize(text: string): string {
  const map: Record<string, string> = {
    a: 'à', b: 'ƀ', c: 'ç', d: 'đ', e: 'é', f: 'ƒ', g: 'ğ', h: 'ĥ',
    i: 'î', j: 'ĵ', k: 'ķ', l: 'ĺ', m: 'ɱ', n: 'ñ', o: 'ô', p: 'þ',
    q: 'ǫ', r: 'ř', s: 'š', t: 'ţ', u: 'û', v: 'ṽ', w: 'ŵ', x: 'ẋ',
    y: 'ý', z: 'ž', A: 'À', B: 'Ɓ', C: 'Ç', D: 'Đ', E: 'É', F: 'Ƒ',
    G: 'Ğ', H: 'Ĥ', I: 'Î', J: 'Ĵ', K: 'Ķ', L: 'Ĺ', M: 'Ṁ', N: 'Ñ',
    O: 'Ô', P: 'Þ', Q: 'Ǫ', R: 'Ř', S: 'Š', T: 'Ţ', U: 'Û', V: 'Ṽ',
    W: 'Ŵ', X: 'Ẋ', Y: 'Ý', Z: 'Ž'
  };
  return '[!!! ' + text.replace(/([^\{\}]+)(?![^\{]*\})/g, (match) => {
    return match.split('').map(c => map[c] || c).join('');
  }) + ' !!!]';
}

